export function createProficiencyMap(
  primary: Position,
  secondary: Position[] = []
): Record<Position, 'Full' | 'Partial' | 'None'> {
  const map: Record<Position, 'Full' | 'Partial' | 'None'> = {
    CF: 'None', SS: 'None', LWF: 'None', RWF: 'None',
    AMF: 'None', CMF: 'None', LMF: 'None', RMF: 'None', DMF: 'None',
    CB: 'None', LB: 'None', RB: 'None', GK: 'None'
  };
  map[primary] = 'Full';
  secondary.forEach(pos => {
    map[pos] = 'Partial';
  });
  return map;
}

